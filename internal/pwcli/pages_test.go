// Nothing downstream of popcornwave.toml knows the names handlers and pages:
// those are what the scaffold writes, and the purpose lists are what everything
// reads. A project that renamed both keeps working.
func TestGenerationFollowsRenamedDirectories(t *testing.T) {
	root := writeRenamedTreeFixture(t)
	generateIn(t, root)

	for _, relative := range []string{
		filepath.Join("site", "routes_pw_gen.go"),
		filepath.Join("site", "layout_pw_gen.go"),
		filepath.Join("site", "docs", "slug_", "page_pw_gen.go"),
		filepath.Join("site", "docs", "slug_", "route_pw_gen.go"),
	} {
		if _, err := os.Stat(filepath.Join(root, relative)); err != nil {
			t.Errorf("the renamed tree did not generate: %v", err)
		}
	}
	// The import path of a route package follows the directory, so a renamed
	// tree cannot keep importing the old one.
	registry := readTestFile(t, filepath.Join(root, "site", "routes_pw_gen.go"))
	for _, want := range []string{
		"package site",
		`example.test/fixture/site/docs/slug_`,
		`mux.HandleFunc("GET /docs/{slug}"`,
	} {
		if !strings.Contains(registry, want) {
			t.Errorf("registry does not contain %q:\n%s", want, registry)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "pages")); !os.IsNotExist(err) {
		t.Error("generation created the default directory in a project that renamed it")
	}
}

// pw new offers the destinations the project configured, not the ones the
// scaffold would have created.
func TestNewPageOffersTheConfiguredTree(t *testing.T) {
	root := writeRenamedTreeFixture(t)
	writeTestFile(t, filepath.Join(root, "config.dev.toml"), "[server]\naddr = \":8080\"\n")
	state, err := loadProjectState(root)
	if err != nil {
		t.Fatal(err)
	}
	destinations := pageDestinations(state)
	if len(destinations) != 1 || destinations[0] != "site" {
		t.Fatalf("page destinations = %v", destinations)
	}
	plan, err := planPage(state, newOptions{
		Kind: newKindPage, Package: destinations[0], Path: "/about", Rung: pageRungTemplate,
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, wrote := plan.creates["site/about/page.pw.html"]; !wrote {
		t.Errorf("the page was not planned inside the configured tree: %v", plan.creates)
	}
}
